package xin.ctkqiang.burpsuite.remote.mobileapp.ui.theme

import androidx.compose.ui.unit.dp

/** 圆角档位。胶囊用一个大到不可能被分辨出直边的值，别拿具体宽高去凑。 */
object BurpRemoteRadius {
    /** 10dp：按钮、输入框等小控件。 */
    val Control = 10.dp

    /** 16dp：卡片。 */
    val Card = 16.dp

    /** 20dp：浮动底栏。 */
    val FloatingNavigation = 20.dp

    /** 999dp：胶囊。 */
    val Capsule = 999.dp
}
