package xin.ctkqiang.burpsuite.remote.protocol

/**
 * 远程控制服务的默认监听端口。
 *
 * 该端口只是默认值，运行期必须允许被配置覆盖。它集中声明在这里，是为了让「默认端口
 * 是 9000」这件事在代码中只有一处事实来源：一旦散落成多处字面量，改动时必然漏掉
 * 某个角落，而漏掉的那一处会表现为「移动端连不上，插件却认为自己一切正常」。
 *
 * 该端口默认监听在局域网地址上，而局域网被视为不可信网络。因此开放它之前，设备配对、
 * 身份认证与命令授权必须先就绪——一个未经认证即可远程控制 Burp 的端口，等同于把拦截
 * 代理和全部流量交给同网段的任何人。
 */
const val DEFAULT_REMOTE_PORT: Int = 9000
