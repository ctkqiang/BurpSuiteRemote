/**
 * Burp Remote —— 安全层 / 本机地址
 *
 * 声明「配对票据该填哪个本机地址」这一问题的端口。把探测动作抽象成接口，是为了让配对
 * 逻辑可以在没有任何网络的环境里被确定性地测试——真实网卡枚举的结果取决于跑测试的那台
 * 机器，一旦把它留在用例里，测试就会在别人的电脑上失败。
 *
 * @author 钟智强
 */

package xin.ctkqiang.burpsuite.remote.security

/**
 * 解析移动端应当连接的本机地址。
 *
 * 实现由传输层提供（见 plan §52 的 `transport/`）：同一个地址既要写进配对票据，也决定了
 * 远程端点应当监听在哪里。两处必须来自同一个判断，否则会出现「二维码指向一个根本没人
 * 监听的地址」这类只有真机联调才会暴露的缺陷。
 */
interface LocalNetworkAddressResolver {
    /**
     * 返回应当写进配对票据的本机地址。
     *
     * 只返回局域网内可达的地址：回环地址对移动端毫无意义，链路本地地址（169.254/16）
     * 通常意味着接口尚未取得租约，同样不可用。
     *
     * @return 点分十进制的 IPv4 地址；当前不存在任何可用的局域网接口时返回 null。
     */
    fun resolveAdvertisedHostAddress(): String?
}
