/**
 * Burp Remote —— 协议层 / 版本
 *
 * 声明线上协议版本这一唯一事实来源。插件与移动端各自持有本常量；一旦任何
 * 序列化名称或消息结构发生变化，必须同时提升版本号，否则旧客户端会把不认识的
 * 字段静默丢弃，表现为难以排查的「数据莫名其妙少了一半」。
 *
 * @author 钟智强
 */

package xin.ctkqiang.burpsuite.remote.protocol

/**
 * 线上协议的版本常量集合。
 *
 * 本对象是协议版本的唯一事实来源。所有消息构造函数都必须读取 [CURRENT_PROTOCOL_VERSION]，
 * 不得在各处字面量硬编码版本号，否则升级协议时必然漏改某一处，而漏掉的那一处
 * 在联调阶段通常最难复现。
 *
 * 版本号只增不减。破坏性变更必须提升版本，并在一段过渡期内保留对旧版本的解析
 * 能力，直到确认不再有旧客户端在线。
 */
object RemoteProtocolVersion {
    /**
     * 当前插件与移动端共同遵守的协议版本。
     *
     * 每条消息都必须携带该值。接收方发现对方版本高于自身时，必须明确拒绝该消息，
     * 而不是尽力解析——「尽力解析」会把协议不匹配伪装成业务数据缺失。
     */
    const val CURRENT_PROTOCOL_VERSION: Int = 1
}
